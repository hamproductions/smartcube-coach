export function createId() {
  if (typeof crypto !== 'undefined' && typeof crypto.randomUUID === 'function') return crypto.randomUUID()
  const bytes = new Uint8Array(16)
  if (typeof crypto !== 'undefined' && typeof crypto.getRandomValues === 'function') crypto.getRandomValues(bytes)
  else for (let index = 0; index < bytes.length; index += 1) bytes[index] = Math.floor(Math.random() * 256)
  bytes[6] = (bytes[6] & 0x0f) | 0x40
  bytes[8] = (bytes[8] & 0x3f) | 0x80
  const hex = [...bytes].map((byte) => byte.toString(16).padStart(2, '0')).join('')
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`
}


export function toEpochMs(timestamp: number | null | undefined) {
  if (timestamp === null || timestamp === undefined) return Date.now()
  if (timestamp > 1_000_000_000_000) return timestamp
  const origin = typeof performance !== 'undefined' && typeof performance.timeOrigin === 'number' ? performance.timeOrigin : 0
  return Math.round(origin + timestamp)
}
